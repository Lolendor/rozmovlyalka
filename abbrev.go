func abbrevIndex(tbl []byte, c byte) int {
	for k, b := range tbl {
		if b == c {
			return k + 1
		}
	}
	return 0
}

// expandAbbreviations — FUN_00465888.
func expandAbbreviations(s []byte) []byte {
	n := len(s)
	var res []byte
	for i := 1; i <= n-1; i++ {
		c := s[i-1]
		if j := abbrevIndex(abbrevTbl1, c); j > 0 && s[i] == '.' {
			res = append(res, abbrevWords1[j]...)
			continue
		}
		if j := abbrevIndex(abbrevTbl2, c); j > 0 {
			res = append(res, abbrevWords2[j]...)
			continue
		}
		res = append(res, c)
	}
	if n > 0 {
		res = append(res, s[n-1])
	}
	return res
}
